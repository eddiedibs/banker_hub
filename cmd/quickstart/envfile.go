package main

import (
	"fmt"
	"os"
	"slices"
	"strings"
)

// shellQuote wraps v in single quotes so `. ./.env` reads it literally,
// even with spaces, $ or quotes in passwords.
func shellQuote(v string) string {
	return "'" + strings.ReplaceAll(v, "'", `'\''`) + "'"
}

// envSection is a commented group of keys in the written file.
type envSection struct {
	comment string
	keys    []string
}

var envLayout = []envSection{
	{"HTTP", []string{"HTTP_ADDR", "API_TOKEN"}},
	{"Storage", []string{"DB_PATH"}},
	{"Sync", []string{"SYNC_INTERVAL", "SYNC_LOOKBACK", "LOG_LEVEL"}},
	{"Binance (read-only API key)", []string{"BINANCE_API_KEY", "BINANCE_API_SECRET"}},
	{"BNC online banking", []string{"BNC_CARD", "BNC_USER_ID", "BNC_PASSWORD"}},
}

// writeEnvFile writes values with mode 0600 through a temp file and rename,
// so a failed write never leaves a half-written .env.
func writeEnvFile(path string, values map[string]string) error {
	var b strings.Builder
	b.WriteString("# Generated by `go run ./cmd/quickstart`. Contains secrets: do not commit.\n")
	written := map[string]bool{}
	for _, sec := range envLayout {
		fmt.Fprintf(&b, "\n# %s\n", sec.comment)
		for _, k := range sec.keys {
			fmt.Fprintf(&b, "%s=%s\n", k, shellQuote(values[k]))
			written[k] = true
		}
	}
	// Keep unknown keys the user added by hand.
	var extra []string
	for k := range values {
		if !written[k] {
			extra = append(extra, k)
		}
	}
	if len(extra) > 0 {
		b.WriteString("\n# Other\n")
		slices.Sort(extra)
		for _, k := range extra {
			fmt.Fprintf(&b, "%s=%s\n", k, shellQuote(values[k]))
		}
	}

	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
